import fs from 'node:fs';
const clean=v=>String(v??'').trim();
const upper=v=>clean(v).toUpperCase();
const args=Object.fromEntries(process.argv.slice(2).filter(x=>x.startsWith('--')&&x.includes('=')).map(x=>{const [k,...v]=x.slice(2).split('=');return[k,v.join('=')]}));
const file=clean(args.file),out=clean(args.output||file);
if(!file||!fs.existsSync(file))throw new Error('MARKETING_DECISION_ARTIFACT_REQUIRED');
const x=JSON.parse(fs.readFileSync(file,'utf8'));
const risks=Array.isArray(x.risks)?x.risks:[];
const facts=Array.isArray(x.facts)?x.facts:[];
const metrics=Array.isArray(x.metrics)?x.metrics:[];
const stop=Array.isArray(x.stopConditions)?x.stopConditions:[];
const financial=/(paid spend|purchase|financial transaction|credit card|payment execution|자동 결제|유료 광고 집행)/i.test(JSON.stringify(x));
const unsupported=facts.some(v=>/guaranteed|확실히|무조건|#1|1위/i.test(JSON.stringify(v)));
const vibe=(facts.length&&metrics.length&&stop.length&&!financial&&!unsupported)?'ACCEPT':'REVIEW';
const primaryAi=(!financial&&!unsupported)?'ACCEPT':'REVIEW';
const joint=vibe==='ACCEPT'&&primaryAi==='ACCEPT'?'ACCEPT':'REVIEW_REQUIRED';
x.decision={...(x.decision||{}),vibe,primaryAi,joint,evaluatedAt:new Date().toISOString(),ownerApprovalGate:false,primaryAiStandingApproval:true};
x.learningCandidate=true;
x.learningRoute='EXISTING_VIBE_LEARNING_MOTOR';
fs.writeFileSync(out,JSON.stringify(x,null,2)+'\n');
console.log('MARKETING_VIBE_DECISION='+vibe);
console.log('MARKETING_JOINT_STATE='+x.decision.joint);
