test('24H learning cycle persists verified experience and external AI distilled stores together',()=>{
  const workflow=read('.github/workflows/vibe2-24h-runner.yml');
  assert.match(workflow,/--experience=\.vibe2\/experience\.json/);
  assert.match(workflow,/--external-ai-distilled=\.vibe2\/external-ai-distilled-knowledge\.json/);
  assert.match(workflow,/git add \.vibe2\/queue\.json[\s\S]*\.vibe2\/experience\.json[\s\S]*\.vibe2\/external-ai-distilled-knowledge\.json/);
  assert.match(workflow,/VIBE2_SPECIALIZED_EXPERIENCE_PERSISTED/);
  assert.match(workflow,/VIBE2_EXTERNAL_AI_ACCEPTED/);
  assert.match(workflow,/VIBE2_LEARNING_ALWAYS_ON: 'true'/);
  assert.match(workflow,/VIBE2_LEARNING_CONCURRENT_WITH_PRODUCTION: 'true'/);
  const idle=workflow.slice(workflow.indexOf('  learning_idle:'),workflow.indexOf('  game_study:'));
  assert.match(idle,/needs\.plan\.outputs\.learning_idle_queued != '0'/);
  assert.match(idle,/execution_lane: learning-idle/);
  assert.match(idle,/lane_max: '1'/);
  assert.doesNotMatch(idle,/lane_max:.*(?:needs\.plan|\|\| '4')/);
  const core=read('.github/workflows/vibe2-continuous-core.yml');
  assert.match(core,/== 'learning-idle' && 'vibe2-learning-single-worker'/);
  assert.match(core,/cancel-in-progress: false/);
  assert.match(idle,/needs\.plan\.outputs\.runner_pressure != 'YES'/);
  assert.match(workflow,/Dispatch next cycle while external runner queue owns physical backpressure/);
  assert.doesNotMatch(workflow,/VIBE2_24H_REFILL_GLOBAL_GATE=DISABLED_EXTERNAL_RUNNER_QUEUE_OWNS_CAPACITY/);
  assert.doesNotMatch(workflow,/VIBE2_24H_REFILL=DEFERRED_TO_SCHEDULE_RUNNER_PRESSURE/);
  assert.match(workflow,/VIBE2_24H_REFILL_RUNNER_PRESSURE_POLICY=EXTERNAL_QUEUE_OWNS_PHYSICAL_BACKPRESSURE/);
  assert.match(workflow,/VIBE2_24H_REFILL=SKIPPED_EXISTING_SCHEDULER/);
  assert.match(workflow,/VIBE2_24H_REFILL=DISPATCHED/);
});

